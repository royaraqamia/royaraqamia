/**
 * The currency table, generated for the app (#653).
 *
 * `shared/currency.ts` is the one place a currency's symbol and its position are
 * decided, and the site reads it directly. The app cannot read TypeScript, so
 * this script emits the same table as a Kotlin object — one source, two clients,
 * the way tokens, recipes, glyphs and copy already work (ADR-0099, ADR-0100).
 *
 * A symbol retyped into Kotlin is a symbol that renders right on one client and
 * wrong on the other — `ر.س` placed before the figure instead of after, or the
 * dollar written without its escape — so the table is emitted rather than
 * mirrored, and `npm run check:currency` fails a pull request that changed
 * `shared/currency.ts` without regenerating.
 *
 * Usage:
 *
 *   node scripts/generate-currency.mjs            # write the Kotlin file
 *   node scripts/generate-currency.mjs --check    # fail if it is stale
 */
import { mkdtemp, readFile, rm, writeFile, mkdir } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

/** The one source of the table. */
export const SOURCE_MODULE = 'shared/currency';

/** Where the app's copy lands. It compiles as-is. */
export const OUTPUT_FILE =
  'android/app/src/main/kotlin/com/royaraqamia/app/shared/CurrencySymbols.kt';

const PACKAGE = 'com.royaraqamia.app.shared';

/**
 * A Kotlin string literal for a value the table may hold.
 *
 * The dollar sign starts a template in Kotlin, so it is escaped — the one symbol
 * in this table that would otherwise turn `$` into a compile error.
 */
export function kotlinString(value) {
  return `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$')}"`;
}

/** The generated file, as one string. Pure: same input, same output. */
export function renderKotlin({ currencies, defaultCurrency, expenseCodes }) {
  const entries = Object.entries(currencies)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(
      ([code, info]) =>
        `            ${kotlinString(code)} to Symbol(${kotlinString(info.symbol)}, prefix = ${
          info.position === 'prefix'
        }, name = ${kotlinString(info.name)}),`
    );

  return [
    '// Generated by `npm run currency:generate` from `shared/currency.ts`.',
    '// Do not edit: change the table and regenerate. `npm run check:currency`',
    '// fails when this file is stale.',
    `package ${PACKAGE}`,
    '',
    '/**',
    ' * Every currency the site knows, as the app writes it (#653).',
    ' *',
    " * `prefix` is the site's own distinction: `$12.50` puts the symbol before the",
    " * figure, `12.50 ر.س` puts it after, and `name` is the Arabic name the site's",
    ' * currency picker shows. The amount itself is formatted with ASCII digits and',
    ' * `en-US` grouping on both clients, so an Arabic-locale phone cannot answer in a',
    ' * second numbering system (ADR-0054).',
    ' */',
    'object CurrencySymbols {',
    '    /** One currency: what is printed, which side, and what it is called. */',
    '    data class Symbol(val symbol: String, val prefix: Boolean, val name: String)',
    '',
    `    /** The site's default when a code is unknown (\`DEFAULT_CURRENCY\`). */`,
    `    const val DEFAULT: String = ${kotlinString(defaultCurrency)}`,
    '',
    '    /** Every code the site resolves; an unknown code falls back to [DEFAULT]. */',
    '    val byCode: Map<String, Symbol> =',
    '        mapOf(',
    ...entries,
    '        )',
    '',
    '    /** The currencies the expense form offers (`EXPENSE_CURRENCIES`). */',
    `    val expenseCodes: List<String> = listOf(${expenseCodes.map(kotlinString).join(', ')})`,
    '}',
    '',
  ].join('\n');
}

/** Load the table through esbuild, which strips the TypeScript. */
async function loadTable() {
  const directory = await mkdtemp(path.join(tmpdir(), 'roy-currency-'));
  const outfile = path.join(directory, 'entry.mjs');
  try {
    const { build } = await import('esbuild');
    await build({
      stdin: {
        contents: `export { CURRENCIES, DEFAULT_CURRENCY, EXPENSE_CURRENCIES } from './${SOURCE_MODULE}';`,
        resolveDir: ROOT,
        loader: 'ts',
      },
      bundle: true,
      platform: 'node',
      format: 'esm',
      target: 'node22',
      outfile,
      logLevel: 'silent',
    });
    const loaded = await import(pathToFileURL(outfile).href);
    return {
      currencies: loaded.CURRENCIES,
      defaultCurrency: loaded.DEFAULT_CURRENCY,
      expenseCodes: loaded.EXPENSE_CURRENCIES.map((currency) => currency.code),
    };
  } finally {
    await rm(directory, { recursive: true, force: true });
  }
}

async function main(argv) {
  const check = argv.includes('--check');
  const contents = renderKotlin(await loadTable());
  const target = path.join(ROOT, OUTPUT_FILE);

  if (!check) {
    await mkdir(path.dirname(target), { recursive: true });
    await writeFile(target, contents, 'utf8');
    return 0;
  }

  let onDisk = null;
  try {
    onDisk = await readFile(target, 'utf8');
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
  if (onDisk !== contents) {
    process.stderr.write(
      `Generated currency table is stale: ${OUTPUT_FILE}\n` +
        'Run `npm run currency:generate` and commit the result.\n'
    );
    return 1;
  }
  return 0;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main(process.argv.slice(2)).then(
    (code) => {
      process.exitCode = code;
    },
    (error) => {
      process.stderr.write(`${error.message}\n`);
      process.exitCode = 1;
    }
  );
}
