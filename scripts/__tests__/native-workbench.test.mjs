import { describe, it, expect } from 'vitest';
import { existsSync, readFileSync, readdirSync } from 'node:fs';
import { join, relative, resolve, dirname, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * The workbench and the plan card (#647, #501), held to the two properties that
 * a rendered frame cannot show.
 *
 * 1. **The workbench is not in the release APK.** It signs in and reads a real
 *    route, so a build that ships must not contain the activity. That is true
 *    today because it is declared only in `src/debug` — and it stays true because
 *    this test fails if it moves. The values it signs in with are no longer
 *    debug-only (#770): the project's URL and publishable key are committed public
 *    configuration (`android/supabase.properties`) that every build type carries,
 *    so what this suite guards now is that no project URL is spelled into source
 *    instead.
 * 2. **The card's copy is the site's, and neither client spells it.** Arabic writes
 *    a letter's marks in more than one order; two spellings render the same and
 *    compare unequal, so a retyped label drifts silently until an exact-text test
 *    misses it. Both clients now read `shared/copy/plan-card.json` through
 *    generated files (ADR-0098), and this suite fails if either starts carrying a
 *    literal again.
 *
 * Checked as source text, like `webview-settings.test.mjs`: the app has no
 * host-side test that can build an activity or a Compose tree.
 */

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const ANDROID = join(ROOT, 'android', 'app', 'src');

function filesUnder(directory) {
  if (!existsSync(directory)) return [];

  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const path = join(directory, entry.name);
    return entry.isDirectory() ? filesUnder(path) : [path];
  });
}

const debugManifest = readFileSync(join(ANDROID, 'debug', 'AndroidManifest.xml'), 'utf8');
const mainManifest = readFileSync(join(ANDROID, 'main', 'AndroidManifest.xml'), 'utf8');
const buildGradle = readFileSync(join(ROOT, 'android', 'app', 'build.gradle'), 'utf8');

describe('the workbench is a debug build', () => {
  it('is declared as its own launcher entry, in the debug manifest only', () => {
    expect(debugManifest).toContain('android:name=".debug.WorkbenchActivity"');
    expect(debugManifest).toContain('android.intent.category.LAUNCHER');

    // The release manifest is the one that ships: no activity, no alias, no entry.
    expect(mainManifest).not.toContain('Workbench');
  });

  it('lives in the debug source set, and nothing in main mentions it', () => {
    const workbench = filesUnder(ANDROID).filter((path) => /Workbench/i.test(path));

    expect(workbench.length).toBeGreaterThan(0);
    for (const path of workbench) {
      expect(relative(ANDROID, path).split(sep)[0]).toBe('debug');
    }
  });

  it('reads the committed public config, and never spells a project URL', () => {
    // #770 made the app sign in, so the project's URL and publishable key are a
    // default-config field every build type carries — committed in
    // `android/supabase.properties`, public by design (RLS is what protects a row),
    // with `local.properties` overriding them per machine.
    expect(buildGradle).toMatch(/buildConfigField "String", "SUPABASE_URL"/);
    expect(buildGradle).toMatch(/buildConfigField "String", "SUPABASE_ANON_KEY"/);
    expect(buildGradle).toContain('supabase.properties');
    expect(buildGradle).toMatch(/localProperties\.getProperty\(key, supabaseProperties/);

    // What must still never happen is a project URL spelled into source: the value
    // is configuration, and a hard-coded one is a build that cannot be pointed at
    // another project.
    for (const path of filesUnder(join(ANDROID, 'main'))) {
      expect(readFileSync(path, 'utf8')).not.toMatch(/https:\/\/[a-z0-9]+\.supabase\.co/);
    }
  });
});

describe('the plan card says what the site says', () => {
  const view = readFileSync(join(ROOT, 'frontend', 'ui', 'account', 'plan-view.tsx'), 'utf8');
  const numbers = readFileSync(
    join(ANDROID, 'main', 'kotlin', 'com', 'royaraqamia', 'app', 'plans', 'UsageCopy.kt'),
    'utf8'
  );
  const generated = readFileSync(
    join(ANDROID, 'main', 'kotlin', 'com', 'royaraqamia', 'app', 'plans', 'PlanCardCopy.kt'),
    'utf8'
  );
  const source = JSON.parse(readFileSync(join(ROOT, 'shared', 'copy', 'plan-card.json'), 'utf8'));

  it('is a generated file, holding the source strings exactly', () => {
    expect(generated).toContain('Generated by `npm run copy:generate`');
    for (const [key, value] of Object.entries(source.strings)) {
      const constant = key.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toUpperCase();
      expect(generated).toContain(`const val ${constant} = "${value}"`);
    }
  });

  it('is NFC, like every other source file', () => {
    expect(generated.normalize('NFC')).toBe(generated);
    expect(JSON.stringify(source.strings).normalize('NFC')).toBe(JSON.stringify(source.strings));
  });

  it('is read by both clients rather than spelled by either', () => {
    expect(view).toContain('PLAN_CARD_COPY');
    for (const value of Object.values(source.strings)) {
      expect(view).not.toContain(value);
      expect(numbers).not.toContain(value);
    }
  });
});
