import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import {
  QURAN_MARKS_UNICODE_RANGE,
  QURAN_NON_MARKS_UNICODE_RANGE,
} from '../shared/contracts/quran-marks.mjs';

/**
 * Emits the two reader faces with their `unicode-range` values written as
 * literals. `next/font/local` requires every option to be an explicit literal —
 * an imported constant is rejected at build time — so the range comes from the
 * shared contract here, at generation time, instead of at runtime.
 *
 * `npm run check:quran-fonts` fails a hand edit that let the two declarations
 * drift from `QURAN_MARK_CODEPOINTS` or from the subset script's keep set.
 */

export const OUTPUT = path.join('frontend', 'ui', 'quran', 'font.ts');

/** The whole file, so `--check` can compare bytes rather than just the ranges. */
export function generate() {
  return [
    '/* Generated by `npm run quran-fonts:generate` from',
    '   `shared/contracts/quran-marks.mjs`. Do not edit: change the mark',
    '   codepoints and regenerate. `npm run check:quran-fonts` fails when stale. */',
    '',
    "import localFont from 'next/font/local';",
    '',
    '/**',
    " * The Quran text's own face: the King Fahd Complex's Uthmani Hafs, cut for the",
    ' * Madinah Mushaf.',
    ' *',
    ' * It lives here rather than in `frontend/shared/fonts.ts` on purpose. The fonts',
    ' * in that module are registered on `<html>`, so every route in the site ships',
    ' * them; these are needed by the reader alone, and `perf:check` measures font',
    ' * preloads per route. Importing them from the Quran layout keeps their',
    " * `@font-face` inside that route's CSS, which is where their bytes are used.",
    ' *',
    " * KFGQPC's EULA grants free use, copying and distribution, but no sale and no",
    ' * modification. The licence ships beside it at',
    ' * `public/fonts/KFGQPC HAFS Uthmanic Script/EULA.txt`; provenance is in',
    ' * `SOURCE.txt`. Amiri Quran is under the OFL, copied beside it.',
    ' */',
    '',
    '/**',
    ' * Three code points are cut out of the Uthmani face (ADR 0067).',
    ' *',
    ' * Version 0.18 maps `U+06DF` (the silent-letter "small high rounded zero", in',
    ' * `كَفَرُوا۟` and `أُو۟لَٰٓئِكَ`) and `U+06E3`/`U+06EB` to its ayah-number',
    ' * rosette, `uni0600` — one em wide and empty — so the mark printed as an',
    ' * ornament in the middle of the word. The face is licensed unmodified, so the',
    ' * fix is a `unicode-range` on either side of the seam: this one claims',
    ' * everything else, `amiriQuranMarks` below claims the three. Both ranges are',
    ' * generated from `QURAN_MARK_CODEPOINTS` in `shared/contracts/quran-marks.mjs`,',
    ' * which is also what subsets the Amiri file.',
    ' */',
    'export const kfgqpcHafs = localFont({',
    '  src: [',
    '    {',
    "      path: '../../../public/fonts/KFGQPC HAFS Uthmanic Script/KFGQPCHAFSUthmanicScript-Regular.woff2',",
    "      weight: '400',",
    "      style: 'normal',",
    '    },',
    '  ],',
    "  variable: '--font-quran',",
    "  display: 'swap',",
    "  adjustFontFallback: 'Arial',",
    '  declarations: [',
    '    {',
    "      prop: 'unicode-range',",
    `      value: '${QURAN_NON_MARKS_UNICODE_RANGE}',`,
    '    },',
    '  ],',
    '});',
    '',
    '/**',
    ' * The three marks the Uthmani face draws as a rosette, set in Amiri Quran',
    ' * instead (ADR 0067).',
    ' *',
    ' * Amiri Quran draws them as the mushaf does — a superscript zero, seen and',
    ' * stop — and is already the licence-clean face the reader used before ADR 0064.',
    ' * Its range is closed to those three, so it never sets a letter: the word stays',
    ' * in the Uthmani face and only the mark crosses the seam. The file is subset to',
    ' * exactly those three code points, and `preload: false` keeps a sura that has',
    ' * none of them from fetching it at first-paint priority.',
    ' */',
    'export const amiriQuranMarks = localFont({',
    '  src: [',
    '    {',
    "      path: '../../../public/fonts/Amiri Quran/AmiriQuran-Regular.woff2',",
    "      weight: '400',",
    "      style: 'normal',",
    '    },',
    '  ],',
    "  variable: '--font-quran-marks',",
    "  display: 'swap',",
    '  adjustFontFallback: false,',
    '  preload: false,',
    `  declarations: [{ prop: 'unicode-range', value: '${QURAN_MARKS_UNICODE_RANGE}' }],`,
    '});',
  ].join('\n');
}

async function main() {
  const expected = `${generate()}\n`;
  const target = path.resolve(process.cwd(), OUTPUT);

  if (process.argv.includes('--check')) {
    const current = await readFile(target, 'utf8').catch(() => '');
    if (current !== expected) {
      console.error(`${OUTPUT} is stale. Run \`npm run quran-fonts:generate\`.`);
      process.exitCode = 1;
    }
    return;
  }

  await writeFile(target, expected);
  console.log(`  ✓ ${OUTPUT}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main();
}
