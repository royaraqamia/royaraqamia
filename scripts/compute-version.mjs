import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { git } from './git-utils.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUTPUT = resolve(ROOT, 'backend', 'config', 'generated', 'app-version.ts');

function readPackageVersion() {
  try {
    const pkg = JSON.parse(readFileSync(resolve(ROOT, 'package.json'), 'utf8'));
    return typeof pkg.version === 'string' && pkg.version ? pkg.version : '0.0.0';
  } catch {
    return '0.0.0';
  }
}

/**
 * Resolves the release version string in a fully deterministic way, tolerating
 * the absence of git and never mutating the repository.
 */
export function resolveReleaseVersion({ appVersionOverride, packageVersion, commitSha, count }) {
  const semver = appVersionOverride || packageVersion;
  const sha7 = (commitSha || '').slice(0, 7) || 'unknown';
  const releaseVersion = `${semver}+build.${count}.${sha7}`;
  return {
    releaseVersion,
    semver,
    commit: commitSha || 'unknown',
    ref: 'unknown',
    env: 'development',
    releasedAt: new Date().toISOString(),
  };
}

/**
 * Decides whether regenerating app-version.ts may touch the working tree.
 * Build hosts always write so the deploy carries its own identity: GitHub
 * Actions sets CI=true, Vercel sets CI/VERCEL=1, and Render sets RENDER=true
 * (the same flag `next.config.js` reads). Local dev/build skips the write,
 * keeping the committed default (and `git status`) pristine.
 * APP_VERSION_WRITE=force|skip overrides either way.
 */
export function shouldWriteAppVersion(env = process.env) {
  if (env.APP_VERSION_WRITE === 'force') return true;
  if (env.APP_VERSION_WRITE === 'skip') return false;
  const ci = String(env.CI ?? '')
    .trim()
    .toLowerCase();
  return (
    ci === 'true' ||
    ci === '1' ||
    env.VERCEL === '1' ||
    Boolean(env.RENDER) ||
    Boolean(env.VERCEL_ENV) ||
    Boolean(env.VERCEL_GIT_COMMIT_SHA)
  );
}

/**
 * The build identity a deploy advertises: the host's own metadata first, the
 * checkout's git second. Render sets RENDER_GIT_COMMIT/RENDER_GIT_BRANCH for a
 * service built from a repo, Vercel sets its equivalents, and a local forced
 * write has neither so it reads the working tree. `env` is `production` on a
 * Render build — the free service is the origin (ADR-0174), and a deploy that
 * answered `development` made every Sentry event look like a local run.
 */
export function resolveBuildIdentity({ env = process.env, commitFromGit, refFromGit }) {
  return {
    commit: env.RENDER_GIT_COMMIT || env.VERCEL_GIT_COMMIT_SHA || commitFromGit || '',
    ref: env.RENDER_GIT_BRANCH || env.VERCEL_GIT_COMMIT_REF || refFromGit || 'unknown',
    env: env.RENDER ? 'production' : env.VERCEL_ENV || 'development',
  };
}

export function main() {
  const appVersionOverride = process.env.APP_VERSION || undefined;
  const packageVersion = readPackageVersion();
  // The build number counts every commit on the deployed branch, not the commits
  // since a release tag: the web has no releases (ADR-0090), and a number that
  // only moved at a release would be identical for every deploy in between.
  const count = git(['rev-list', '--count', 'HEAD'], '0');
  const identity = resolveBuildIdentity({
    commitFromGit: git(['rev-parse', 'HEAD'], ''),
    refFromGit: git(['symbolic-ref', '--short', 'HEAD'], ''),
  });

  const resolved = resolveReleaseVersion({
    appVersionOverride,
    packageVersion,
    commitSha: identity.commit || undefined,
    count,
  });

  resolved.ref = identity.ref;
  resolved.env = identity.env;

  const content =
    '// Auto-generated by scripts/compute-version.mjs — do not edit by hand.\n' +
    '// Regenerated by prebuild/predev on CI, Vercel and Render; locals use the\n' +
    '// committed default (override with APP_VERSION_WRITE=force).\n' +
    'export const appVersion = {\n' +
    `  releaseVersion: '${resolved.releaseVersion}',\n` +
    `  semver: '${resolved.semver}',\n` +
    `  commit: '${resolved.commit}',\n` +
    `  ref: '${resolved.ref}',\n` +
    `  env: '${resolved.env}',\n` +
    `  releasedAt: '${resolved.releasedAt}',\n` +
    '} as const;\n';

  let existing;
  try {
    existing = readFileSync(OUTPUT, 'utf8');
  } catch {
    // Missing file (fresh checkout variant) — always generate so tsc/tests work.
  }

  // Skip silently when running outside CI/Vercel/Render and the committed
  // default exists.
  if (existing !== undefined && !shouldWriteAppVersion()) {
    return resolved;
  }
  if (existing === content) {
    return resolved;
  }

  mkdirSync(dirname(OUTPUT), { recursive: true });
  writeFileSync(OUTPUT, content, 'utf8');
  return resolved;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
