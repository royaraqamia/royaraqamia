/**
 * One copy source, two clients (#647, ADR-0098).
 *
 * Arabic writes a word's combining marks in two orders — fatha/damma/kasra then
 * shadda, or shadda then the vowel. They render identically and compare unequal,
 * so a label retyped into Kotlin is a label that fails an exact-text test later
 * while looking right on a device. The plan card used to carry that hazard as a
 * comment ("copied from the site, byte for byte"); this script makes it a fact
 * instead.
 *
 * Each `shared/copy/<surface>.json` names the two files it is generated into and
 * the words themselves. It emits
 *
 *   - the site's module, a frozen object the component imports;
 *   - the app's object, one `const val` per string.
 *
 * Every output is committed, so a pull request that edits a string without
 * regenerating fails CI (`npm run check:copy`), and `npm run check:parity` fails
 * a string the reference component does not render.
 *
 * Usage:
 *
 *   node scripts/generate-copy.mjs            # write every output
 *   node scripts/generate-copy.mjs --check    # fail if they are stale
 */
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

export const SOURCE_DIR = 'shared/copy';

/** `planFree` -> `PLAN_FREE`, the app's name for the same string. */
export function constantName(key) {
  return key.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toUpperCase();
}

/** `{date}` -> `['date']`, in the order the sentence uses them. */
export function placeholders(value) {
  return [...value.matchAll(/\{([a-z][a-zA-Z0-9]*)\}/g)].map((match) => match[1]);
}

/**
 * Reject a source the emitters would otherwise render as `undefined`, and reject
 * a string that reads as copy but is one client's mistake: an empty label, a
 * quote that would end a Kotlin literal, or a placeholder with no closing brace.
 */
export function validate(source, file = SOURCE_DIR) {
  const errors = [];
  const where = `${file}`;

  for (const field of ['surface', 'component']) {
    if (typeof source[field] !== 'string' || source[field].length === 0) {
      errors.push(`${where}: no "${field}"`);
    }
  }
  for (const client of ['web', 'native']) {
    const entry = source[client];
    if (!entry || typeof entry.file !== 'string' || entry.file.length === 0) {
      errors.push(`${where}: "${client}.file" is required`);
    }
  }
  if (
    typeof source.web?.export !== 'string' ||
    !/^[A-Z][A-Z0-9_]*$/.test(source.web?.export ?? '')
  ) {
    errors.push(`${where}: "web.export" must be an UPPER_SNAKE identifier`);
  }
  if (
    typeof source.native?.object !== 'string' ||
    !/^[A-Z][A-Za-z0-9]*$/.test(source.native?.object ?? '')
  ) {
    errors.push(`${where}: "native.object" must be a Kotlin object name`);
  }

  const strings = source.strings ?? {};
  const keys = Object.keys(strings);
  if (keys.length === 0) {
    errors.push(`${where}: "strings" is empty`);
  }

  for (const key of keys) {
    if (!/^[a-z][a-zA-Z0-9]*$/.test(key)) {
      errors.push(`${where}: "${key}" is not a camelCase key`);
    }
    const value = strings[key];
    if (typeof value !== 'string' || value.trim().length === 0) {
      errors.push(`${where}: "${key}" is empty`);
      continue;
    }
    const opens = (value.match(/\{/g) ?? []).length;
    const closes = (value.match(/\}/g) ?? []).length;
    if (opens !== closes) {
      errors.push(`${where}: "${key}" has an unbalanced "{" or "}"`);
    }
    if (/["\\$\n]/.test(value.replace(/\{[a-z][a-zA-Z0-9]*\}/g, ''))) {
      errors.push(
        `${where}: "${key}" must be one line with no quote, backslash or dollar sign ` +
          '(a placeholder is `{name}`, and both emitters would need escaping otherwise)'
      );
    }
  }

  return errors;
}

/** The site's module: one frozen object, imported by name. */
export function renderWeb(source, where = `${SOURCE_DIR}/${source.component}.json`) {
  const { export: name, file } = source.web;
  const lines = [
    '// Generated by `npm run copy:generate` from',
    `// \`${where}\`. Do not edit: change the source`,
    '// and regenerate. `npm run check:copy` fails when this file is stale.',
    '',
    '/**',
    ` * The ${source.component} in the site's words (#647, ADR-0098). The app draws`,
    ' * the same strings from the same source, so a label cannot be right on one',
    ' * client and wrong on the other.',
    ' *',
    ' * A `{name}` is a placeholder the caller substitutes, not a format string.',
    ' */',
    `export const ${name} = {`,
  ];
  for (const [key, value] of Object.entries(source.strings)) {
    lines.push(`  ${key}: '${value.replace(/'/g, "\\'")}',`);
  }
  lines.push('} as const;', '', `export type ${exportTypeName(name)} = typeof ${name};`, '');
  return { file, contents: lines.join('\n') };
}

/** `PLAN_CARD_COPY` -> `PlanCardCopy`, the object's Kotlin name. */
function exportTypeName(name) {
  return `${name
    .toLowerCase()
    .replace(/_([a-z0-9])/g, (_, letter) => letter.toUpperCase())
    .replace(/^[a-z]/, (letter) => letter.toUpperCase())}Strings`;
}

/** The app's object: the same words as constants the card reads. */
export function renderNative(source, where = `${SOURCE_DIR}/${source.component}.json`) {
  const { object, file } = source.native;
  const lines = [
    '// Generated by `npm run copy:generate` from',
    `// \`${where}\`. Do not edit: change the source`,
    '// and regenerate. `npm run check:copy` fails when this file is stale.',
    'package com.royaraqamia.app.plans',
    '',
    '/**',
    ` * The ${source.component} in the site's words (#647, ADR-0098). One source,`,
    ' * two clients: these constants come from the same file that writes the site',
    ` * module (\`${where}\`), so Arabic that renders`,
    ' * identically but compares unequal cannot drift between them.',
    ' *',
    ' * A `{name}` is a placeholder the card substitutes, not a format string.',
    ' */',
    `object ${object} {`,
  ];
  for (const [key, value] of Object.entries(source.strings)) {
    lines.push(`    const val ${constantName(key)} = "${value}"`);
  }
  lines.push('}', '');
  return { file, contents: lines.join('\n') };
}

/** Every copy source in the tree, keyed by repo-relative output path. */
export async function sources(root = ROOT) {
  const directory = path.join(root, SOURCE_DIR);
  const entries = (await readdir(directory)).filter((entry) => entry.endsWith('.json')).sort();
  return Promise.all(
    entries.map(async (entry) => ({
      file: `${SOURCE_DIR}/${entry}`,
      source: JSON.parse(await readFile(path.join(directory, entry), 'utf8')),
    }))
  );
}

/** Every output, keyed by repo-relative path, without touching the disk. */
export async function generate(root = ROOT) {
  const files = new Map();
  const errors = [];
  for (const { file, source } of await sources(root)) {
    errors.push(...validate(source, file));
    for (const rendered of [renderWeb(source, file), renderNative(source, file)]) {
      files.set(rendered.file, rendered.contents);
    }
  }
  if (errors.length > 0) {
    throw new Error(errors.join('\n'));
  }
  return files;
}

async function main(argv) {
  const check = argv.includes('--check');
  const files = await generate();

  if (!check) {
    for (const [file, contents] of files) {
      const target = path.join(ROOT, file);
      await mkdir(path.dirname(target), { recursive: true });
      await writeFile(target, contents, 'utf8');
    }
    return 0;
  }

  const stale = [];
  for (const [file, contents] of files) {
    let onDisk = null;
    try {
      onDisk = await readFile(path.join(ROOT, file), 'utf8');
    } catch (error) {
      if (error.code !== 'ENOENT') throw error;
    }
    if (onDisk !== contents) stale.push(file);
  }
  if (stale.length > 0) {
    process.stderr.write(
      `Generated copy is stale: ${stale.join(', ')}\n` +
        'Run `npm run copy:generate` and commit the result.\n'
    );
    return 1;
  }
  return 0;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main(process.argv.slice(2)).then(
    (code) => {
      process.exitCode = code;
    },
    (error) => {
      process.stderr.write(`${error.message}\n`);
      process.exitCode = 1;
    }
  );
}
