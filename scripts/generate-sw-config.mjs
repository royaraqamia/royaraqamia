import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const OUTPUT = 'public/sw-push-config.js';

/**
 * Emits the VAPID public key as a plain script the service worker imports.
 * Web Push endpoint rotation is handled by `pushsubscriptionchange`, which is
 * delivered INSIDE the service worker — usually while no page is open — so the
 * key cannot be injected through the client JS bundle like `NEXT_PUBLIC_*`
 * values normally are.
 *
 * Mirrors how `public/sw-version.js` is produced: generated every
 * predev/prebuild, git-ignored, and safely absent in raw test runs (the
 * service worker falls back to a disabled config).
 */
function readEnvValue(name) {
  if (process.env[name]) return process.env[name];
  for (const file of ['.env.local', '.env']) {
    if (!existsSync(file)) continue;
    try {
      const contents = readFileSync(file, 'utf8');
      for (const line of contents.split('\n')) {
        const match = line.match(/^\s*(?:export\s+)?([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
        if (!match || match[1] !== name) continue;
        const value = match[2].trim().replace(/^["']|["']$/g, '');
        if (value.length > 0) return value;
      }
    } catch {
      // Fall through to the next candidate file.
    }
  }
  return '';
}

function main() {
  const publicKey = readEnvValue('NEXT_PUBLIC_VAPID_PUBLIC_KEY');
  const safeKey = publicKey.replace(/['\\\s]/g, '');
  writeFileSync(
    OUTPUT,
    `// Auto-generated by scripts/generate-sw-config.mjs — do not edit by hand.\n` +
      `self.PUSH_CONFIG = { publicKey: '${safeKey}' };\n`
  );
  console.log(`  ✓ ${OUTPUT} → ${safeKey ? `${safeKey.slice(0, 8)}…` : '(no VAPID key)'}`);
}

main();
