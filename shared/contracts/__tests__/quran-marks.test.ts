import { readFileSync } from 'node:fs';
import path from 'node:path';
import { describe, expect, it } from 'vitest';

import {
  QURAN_MARK_CODEPOINTS,
  QURAN_MARKS_UNICODE_RANGE,
  QURAN_NON_MARKS_UNICODE_RANGE,
  unicodeRangeExcluding,
  unicodeRangeFor,
} from '@/shared/contracts/quran-marks.mjs';

/**
 * The seam between the two reader faces is three code points written down in
 * one place (ADR 0067). These assertions keep both `unicode-range`
 * declarations derived from that place, and keep the file behind the marks
 * face at the size of the declaration rather than the size of the whole face.
 */

const ROOT = path.resolve(import.meta.dirname, '..', '..', '..');

function parseRanges(value: string): [number, number][] {
  return value.split(', ').map((part) => {
    const bounds = part
      .slice(2)
      .split('-')
      .map((hex) => parseInt(hex, 16));
    const start = bounds[0] ?? 0;
    return [start, bounds[1] ?? start];
  });
}

describe('the mark codepoints', () => {
  it('are the three KFGQPC v0.18 rosette mappings', () => {
    expect(QURAN_MARK_CODEPOINTS).toEqual([0x06df, 0x06e3, 0x06eb]);
  });

  it('renders the marks face range from them', () => {
    expect(QURAN_MARKS_UNICODE_RANGE).toBe('U+06DF, U+06E3, U+06EB');
    expect(unicodeRangeFor([0x06df])).toBe('U+06DF');
  });

  it('renders the Uthmani exclusion range from them', () => {
    expect(QURAN_NON_MARKS_UNICODE_RANGE).toBe(
      'U+0000-06DE, U+06E0-06E2, U+06E4-06EA, U+06EC-10FFFF'
    );
    expect(unicodeRangeExcluding([0x10ffff], 0x10fffd)).toBe('U+10FFFD-10FFFE');
  });

  it('partitions the whole Unicode space without a gap or an overlap', () => {
    const ranges = [
      ...parseRanges(QURAN_MARKS_UNICODE_RANGE),
      ...parseRanges(QURAN_NON_MARKS_UNICODE_RANGE),
    ].sort((a, b) => a[0] - b[0]);

    expect(ranges[0]?.[0]).toBe(0);
    expect(ranges.at(-1)?.[1]).toBe(0x10ffff);
    for (let index = 1; index < ranges.length; index += 1) {
      expect(ranges[index]?.[0]).toBe((ranges[index - 1]?.[1] ?? 0) + 1);
    }
  });
});

describe('the shipped marks face', () => {
  it('carries three glyphs, not a whole Quran face', () => {
    const file = path.join(ROOT, 'public/fonts/Amiri Quran/AmiriQuran-Regular.woff2');
    expect(readFileSync(file).length).toBeLessThanOrEqual(1024);
  });

  it('keeps the build on the same codepoints the faces declare', () => {
    const font = readFileSync(path.join(ROOT, 'frontend/ui/quran/font.ts'), 'utf8');
    const subset = readFileSync(path.join(ROOT, 'scripts/subset-fonts.mjs'), 'utf8');

    expect(font).toContain('Generated by `npm run quran-fonts:generate`');
    expect(font).toContain('preload: false');
    expect(subset).toContain('QURAN_MARK_CODEPOINTS');
  });
});
