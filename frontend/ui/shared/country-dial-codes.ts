export interface CountryDialCode {
  /** ISO 3166-1 alpha-2, unique key for list rendering. */
  iso: string;
  /** Arabic display name (primary UI language). */
  nameAr: string;
  /** International dial code without the leading "+". */
  dial: string;
  flag: string;
}

/** Derives the regional-indicator flag emoji from an ISO 3166-1 alpha-2 code. */
function flagFromIso(iso: string): string {
  return iso
    .toUpperCase()
    .replace(/[A-Z]/g, (letter) => String.fromCodePoint(127397 + letter.charCodeAt(0)));
}

