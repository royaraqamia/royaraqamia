export const COUNTRY_DIAL_CODES: readonly CountryDialCode[] = [
  DEFAULT_COUNTRY,
  ...COUNTRY_SEEDS.map((seed) => ({ ...seed, flag: flagFromIso(seed.iso) })),
];

const COUNTRY_BY_ISO: ReadonlyMap<string, CountryDialCode> = new Map(
  COUNTRY_DIAL_CODES.map((country) => [country.iso, country])
);

/** Resolves an ISO 3166-1 alpha-2 code (case-insensitive) to its dial-code entry. */
export function getCountryByIso(iso: string | null | undefined): CountryDialCode | null {
  if (!iso) return null;
  return COUNTRY_BY_ISO.get(iso.toUpperCase()) ?? null;
}
