/**
 * The emoji a member can put in a message or a comment.
 *
 * It is a catalog rather than a library call. The third-party pickers index
 * their search on English names, and this site's members search in Arabic, so a
 * library would draw a sheet whose search does not find «قلب». Every entry
 * therefore carries its own keywords in both languages, and the sheet searches
 * them the way an Arabic keyboard types them: no diacritics, either alef, either
 * ya, and a ta marbuta that matches a ha.
 *
 * The set is curated rather than complete — the emoji a conversation actually
 * uses, not all 3,000 Unicode names — and it is one module so a future library
 * can replace `searchEmoji` and `EMOJI_CATALOG` without touching the field or
 * the sheet. Skin tones are deliberately absent: a default hand is the tone
 * every platform draws, and a per-member preference is a settings question this
 * file cannot answer.
 */

