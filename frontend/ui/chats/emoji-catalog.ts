/**
 * The surface's words for the sheet: the button's name, the search and its
 * empty answer, the recent tab and the nine category names, worded by the
 * surface that draws the field. They live beside the catalog so a
 * field can type its labels without importing the sheet, which is a chunk the
 * member only downloads when they open it.
 */
export interface ChatEmojiLabels {
  open: string;
  /** What the smiley becomes while the tray is open: the keyboard switch. */
  keyboard: string;
  search: string;
  noResults: string;
  recent: string;
  categories: Record<EmojiCategory, string>;
}

/** One entry by its glyph, for the recent list, which stores glyphs. */
export const EMOJI_BY_GLYPH: ReadonlyMap<string, EmojiEntry> = new Map(
  EMOJI_CATEGORIES.flatMap((category) => EMOJI_CATALOG[category]).map((entry) => [entry[0], entry])
);

/** The Arabic a searcher types, spelled the way the words are indexed. */
export function normalizeEmojiText(value: string): string {
  return value
    .toLowerCase()
    .replace(/[أإآٱ]/g, 'ا')
    .replace(/ى/g, 'ي')
    .replace(/ؤ/g, 'و')
    .replace(/ئ/g, 'ي')
    .replace(/ة/g, 'ه')
    .replace(/[\u064B-\u0652\u0640]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * The catalog with its keywords already normalised: a search runs on every
 * keystroke, and rebuilding the index each time would make the sheet's own
 * search the slowest thing in the composer.
 */
const INDEX: readonly { entry: EmojiEntry; words: readonly string[] }[] = EMOJI_CATEGORIES.flatMap(
  (category) =>
    EMOJI_CATALOG[category].map((entry) => ({
      entry,
      words: `${normalizeEmojiText(entry[1])} ${normalizeEmojiText(entry[2])}`
        .split(' ')
        .filter(Boolean),
    }))
);

/**
 * Entries whose keywords start with every word typed.
 *
 * Prefixes rather than substrings, because «قل» should find «قلب» and «سلام»
 * without matching every word that happens to contain those letters. English and
 * Arabic are searched together, so a member typing in either finds the same set.
 */
export function searchEmoji(query: string): EmojiEntry[] {
  const tokens = normalizeEmojiText(query).split(' ').filter(Boolean);
  if (tokens.length === 0) return [];

  return INDEX.filter(({ words }) =>
    tokens.every((token) => words.some((word) => word.startsWith(token)))
  ).map(({ entry }) => entry);
}
